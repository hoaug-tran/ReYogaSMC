public func loc(_ key: LocalizedKey) -> String {
    key.localized
}

public func localizedMessage(_ source: String, _ arguments: String...) -> String {
    renderLocalizedMessage(source, arguments: arguments.map { $0 as CVarArg }, bundle: .main)
}

func renderLocalizedMessage(_ source: String, arguments: [CVarArg], bundle: Bundle) -> String {
    let format = bundle.localizedString(forKey: source, value: source, table: nil)
    return arguments.isEmpty ? format : String(format: format, locale: Locale.current, arguments: arguments)
}
