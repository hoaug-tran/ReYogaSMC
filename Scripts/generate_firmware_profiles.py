"""Generate the read-only kernel profile table from reviewed hardware profiles."""
import argparse
import json
import pathlib
import re
ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "ReYogaSMC/ReYogaFirmwareProfiles.hpp"
def render(profiles):
    rows = []
    hashes = set()
    for profile in sorted(profiles, key=lambda item: item["id"]):
        sensors = profile.get("native_telemetry")
        if sensors is None:
            continue
        if profile.get("schema_version") != 1 or profile.get("kind") != "acpi" or not isinstance(sensors, list) or len(sensors) != 4:
            raise ValueError("Native telemetry requires four reviewed ACPI fields")
        if not all(isinstance(profile.get(key), str) for key in ("id", "name")):
            raise ValueError("Native profile identity must be text")
        for sensor in sensors:
            if not re.fullmatch(r"[A-Z_][A-Z0-9_]{3}", sensor["field"]):
                raise ValueError("Invalid ACPI field")
            if type(sensor["scale"]) is not int or not 1 <= sensor["scale"] <= 1000:
                raise ValueError("Invalid sensor scale")
        namespace = profile.get("ec_path", "")
        if not isinstance(namespace, str) or not re.fullmatch(r"\\[A-Z_][A-Z0-9_]{0,3}(?:\.[A-Z_][A-Z0-9_]{0,3})*", namespace):
            raise ValueError("Native telemetry requires an absolute reviewed EC namespace")
        fields = ", ".join(json.dumps(namespace + "." + sensor["field"]) for sensor in sensors)
        scales = ", ".join(str(sensor["scale"]) for sensor in sensors)
        reviewed = profile.get("reviewed_aml_hashes", [])
        if not reviewed:
            raise ValueError("Native telemetry requires reviewed AML hashes")
        for digest in reviewed:
            if not re.fullmatch("[a-f0-9]{64}", digest) or digest in hashes:
                raise ValueError("Invalid or duplicate AML digest")
            hashes.add(digest)
            strings = ", ".join(json.dumps(profile[key]) for key in ("id", "name"))
            rows.append('    {"' + digest + '", ' + strings + ', {' + fields + '}, {' + scales + '}},')
    if not rows:
        raise ValueError("No reviewed native telemetry profiles")
    return """// Generated by Scripts/generate_firmware_profiles.py; edit HardwareProfiles instead.
#ifndef ReYogaFirmwareProfiles_hpp
#define ReYogaFirmwareProfiles_hpp
struct ReYogaNativeProfile {
    const char *digest;
    const char *id;
    const char *name;
    const char *fields[4]; // Absolute ACPI paths: fan 1/2 RPM, CPU/GPU Celsius.
    unsigned scales[4];
};
static constexpr ReYogaNativeProfile ReYogaNativeProfiles[] = {
""" + "\n".join(rows) + """
};
#endif
"""
def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = render([json.loads(path.read_text(encoding="utf-8")) for path in (ROOT / "HardwareProfiles").glob("*.json")])
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
            parser.exit(1, "Kernel firmware profiles are stale; run Scripts/generate_firmware_profiles.py\n")
    else:
        with OUTPUT.open("w", encoding="utf-8", newline="\n") as output:
            output.write(result)
if __name__ == "__main__":
    main()
